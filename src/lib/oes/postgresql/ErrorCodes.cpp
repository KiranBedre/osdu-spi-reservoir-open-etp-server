PGErrorCode lookupErrorCodeByName(const char* str) {
    if (!str || *str == '\0') {
        return PG_XX000;
    }
    auto found = error_codes_map.find(str);
    if (found == error_codes_map.end()) {
        return PG_XX000;
    }
    return found->second;
}

